const fs=require('node:fs');
const path=require('node:path');
const core=require('../lib/catalogue-core.js');
const root=path.resolve(__dirname,'..');
const source=JSON.parse(fs.readFileSync(path.join(root,'data/catalogue.json'),'utf8'));
const catalogue=core.validateCatalogue(source);
const serialized=JSON.stringify(catalogue,null,2).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
fs.writeFileSync(path.join(root,'data/catalogue-data.js'),'// Generated by npm run build:data. Edit catalogue.json instead.\nconst MAV_CATALOGUE = '+serialized+';\n');
console.log('Catalogue validated:',catalogue.items.length,'properties; mode:',catalogue.mode);
